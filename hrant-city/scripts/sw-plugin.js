// Vite plugin that emits sw.js at build time with a precache list of every built file,
// so the game works fully offline after the first visit (PWA).
import fs from 'node:fs';
import path from 'node:path';

function walk(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return fs.statSync(p).isDirectory() ? walk(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}

export function swPlugin() {
  return {
    name: 'hrant-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = new Set(['./', './index.html']);
      for (const f of Object.keys(bundle)) files.add('./' + f);
      for (const f of walk(path.resolve('public'))) files.add('./' + f);
      const list = [...files].sort();
      let h = 0;
      for (const f of list) for (let i = 0; i < f.length; i++) h = (h * 31 + f.charCodeAt(i)) | 0;
      const version = 'hrant-city-' + (h >>> 0).toString(36) + '-' + Date.now().toString(36);
      const code = `// Generated by scripts/sw-plugin.js
const CACHE = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(list)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches['delete'](k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match('./index.html')))
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: code });
    },
  };
}
